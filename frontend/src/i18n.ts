const DICTS: Record<Lang, Record<TKey, string>> = { es, en };

/** Traduce una clave con parámetros {nombre}. Claves desconocidas se devuelven tal cual. */
export function translate(lang: Lang, key: string, params?: LogParams): string {
  const dict = DICTS[lang] as Record<string, string>;
  let s = dict[key] ?? (es as Record<string, string>)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  // Tipo de ruta traducido dentro de los mensajes
  if (lang === 'es') s = s.replace(/^Ruta static /, 'Ruta estática ').replace(/^Ruta rip /, 'Ruta RIP ');
  else s = s.replace(/^static route /, 'Static route ').replace(/^rip route /, 'RIP route ');
  return s;
}
